-- Isolated test schema derived from live metadata; contains no production rows.
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA auth; CREATE TABLE auth.users (id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
GRANT USAGE ON SCHEMA auth TO anon, authenticated;
CREATE FUNCTION public.uuid_generate_v4() RETURNS uuid LANGUAGE sql AS $$ SELECT gen_random_uuid() $$;
CREATE TABLE public.hosts (
  host_id uuid NOT NULL,
  display_name character varying DEFAULT 'Host'::character varying,
  avatar_url character varying
);
CREATE TABLE public.events (
  event_id uuid DEFAULT uuid_generate_v4() NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  host_id uuid NOT NULL,
  title character varying NOT NULL,
  date date NOT NULL,
  time character varying,
  location character varying,
  photo_url character varying,
  description text DEFAULT ''::text NOT NULL,
  contributions_enabled boolean DEFAULT false NOT NULL,
  contributions_frozen boolean DEFAULT false NOT NULL,
  contributions_custom_title character varying,
  url_code bigint NOT NULL,
  url_string character varying NOT NULL,
  deleted_by_host boolean DEFAULT false
);
CREATE TABLE public.guests (
  guest_id uuid DEFAULT uuid_generate_v4() NOT NULL,
  created_at timestamp with time zone DEFAULT now(),
  event_id uuid,
  display_name character varying NOT NULL
);
CREATE TABLE public.contributions (
  contribution_id uuid DEFAULT uuid_generate_v4() NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  event_id uuid NOT NULL,
  description character varying NOT NULL,
  requested boolean DEFAULT false NOT NULL,
  contributor_id uuid,
  claimed_comment character varying
);
CREATE TABLE public.page_visits (
  visit_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  event_id uuid NOT NULL,
  visited_at timestamp with time zone DEFAULT now() NOT NULL,
  user_is_host boolean DEFAULT false NOT NULL
);
CREATE TABLE public.testing (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  content character varying
);
ALTER TABLE public.contributions ADD CONSTRAINT contributions_pkey PRIMARY KEY (contribution_id);
ALTER TABLE public.events ADD CONSTRAINT events_pkey PRIMARY KEY (event_id);
ALTER TABLE public.events ADD CONSTRAINT events_url_code_key UNIQUE (url_code);
ALTER TABLE public.guests ADD CONSTRAINT guests_pkey PRIMARY KEY (guest_id);
ALTER TABLE public.hosts ADD CONSTRAINT hosts_pkey PRIMARY KEY (host_id);
ALTER TABLE public.testing ADD CONSTRAINT notes_id_key UNIQUE (id);
ALTER TABLE public.testing ADD CONSTRAINT notes_pkey PRIMARY KEY (id);
ALTER TABLE public.page_visits ADD CONSTRAINT page_visits_pkey PRIMARY KEY (visit_id);
ALTER TABLE public.guests ADD CONSTRAINT unique_guest_names_per_event UNIQUE (event_id, display_name);
ALTER TABLE public.contributions ADD CONSTRAINT contributions_contributor_id_fkey FOREIGN KEY (contributor_id) REFERENCES guests(guest_id);
ALTER TABLE public.contributions ADD CONSTRAINT contributions_event_id_fkey FOREIGN KEY (event_id) REFERENCES events(event_id);
ALTER TABLE public.events ADD CONSTRAINT events_host_id_fkey FOREIGN KEY (host_id) REFERENCES hosts(host_id);
ALTER TABLE public.guests ADD CONSTRAINT guests_event_id_fkey FOREIGN KEY (event_id) REFERENCES events(event_id);
ALTER TABLE public.hosts ADD CONSTRAINT hosts_host_id_fkey FOREIGN KEY (host_id) REFERENCES auth.users(id);
ALTER TABLE public.page_visits ADD CONSTRAINT page_visits_event_id_fkey FOREIGN KEY (event_id) REFERENCES events(event_id);
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
CREATE SCHEMA storage;
CREATE TABLE storage.objects (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), bucket_id text NOT NULL, name text NOT NULL, UNIQUE(bucket_id,name));
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA storage TO anon, authenticated, service_role;
GRANT ALL ON storage.objects TO anon, authenticated, service_role;
CREATE POLICY "Enable insert for authenticated users only" ON storage.objects FOR ALL TO authenticated USING (true) WITH CHECK (true);
